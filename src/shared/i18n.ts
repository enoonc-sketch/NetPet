// 1.5.0 中英文界面（主进程、主面板、小面板、宠物气泡、托盘菜单、通知共用）。
// 用法：t('key', { 参数 })，文字里的 {name} 会被替换。找不到的键先退回中文，再退回键名本身。
// 新增文字时两个字典都要加同一个键（单元测试会检查两边键一致、占位符一致）。
export type Lang = 'zh' | 'en';
export type Dict = Record<string, string>;
export const LANG_SETTINGS = ['auto', 'zh', 'en'];
let cur: Lang = 'zh';
export function setLang(l: any) { cur = l === 'en' ? 'en' : 'zh'; }
export function getLang(): Lang { return cur; }
/** 设置值 → 实际语言。auto：系统语言（app.getLocale()）以 zh 开头用中文，其余用英文；读不到时用中文。 */
export function resolveLang(setting: any, locale: any): Lang {
  if (setting === 'zh' || setting === 'en') return setting;
  const l = String(locale || '').toLowerCase();
  if (!l || l.startsWith('zh')) return 'zh';
  return 'en';
}
const own = (d: Dict, k: string) => Object.prototype.hasOwnProperty.call(d, k);
export function has(key: string) { return own(zh, key); }
export function t(key: string, p?: Record<string, any>): string {
  const d = cur === 'en' ? en : zh;
  let s = own(d, key) ? d[key] : own(zh, key) ? zh[key] : key;
  if (p) s = s.replace(/\{(\w+)\}/g, (m, k) => (p[k] == null ? m : String(p[k])));
  return s;
}
/** 文字里的占位符名（排序去重），单元测试用。 */
export function placeholders(s: string): string[] { return [...new Set((String(s).match(/\{(\w+)\}/g) || []).map((x) => x.slice(1, -1)))].sort(); }

